import os
import re
from dataclasses import replace

from config import Settings, load_settings, save_preset
from services.ai_service import generate_sentences
from services.anki_service import send_to_anki
from services.kindle_service import extract_words_from_kindle_db
from services.tts_service import generate_audio
from services.word_service import add_word, has_word


def cleanup_audio(paths):
    for path in paths:
        try:
            if path and os.path.exists(path):
                os.remove(path)
        except Exception as e:
            print("Erro ao deletar áudio:", e)


def split_words_input(raw_text):
    if not raw_text:
        return [], []

    invalid_formats = []

    normalized = (
        raw_text.replace("\r", "\n")
        .replace(",", " ")
        .replace(";", " ")
        .replace("|", " ")
    )

    def reject_spaced_parenthesis(match):
        invalid_formats.append(match.group())
        return " "

    normalized = re.sub(
        r"(?<!\S)[^\s()]+\s+\([^)]*\)", reject_spaced_parenthesis, normalized
    )

    words = []
    for item in normalized.split():
        clean_item = item.strip()
        if not clean_item:
            continue

        # Ignore detached parenthesis fragments generated by invalid format.
        if clean_item.startswith("(") and clean_item.endswith(")"):
            continue

        words.append(clean_item)

    return words, invalid_formats


def process_word(word: str, settings: Settings) -> str:
    word = (word or "").strip()
    if not word:
        return "invalid"

    if has_word(word):
        print(f"Aviso: palavra '{word}' ja foi processada anteriormente\n")
        return "duplicate"

    print(f"\nGerando frases para: {word}...\n")
    try:
        sentences_data = generate_sentences(word, settings)
    except Exception as e:
        print(f"Erro ao gerar frases: {e}\n")
        return "error"

    sent_cards = 0

    for item in sentences_data:
        sentence = item["sentence"].strip()
        translation = item["translation"].strip()

        print(sentence)

        try:
            audio_path = generate_audio(sentence)
        except Exception as e:
            print(f"Erro ao gerar áudio: {e}")
            continue
        if not audio_path:
            continue

        cloze = f"{{{{c1::{sentence}}}}}"
        try:
            send_to_anki(cloze, translation, audio_path, settings)
            sent_cards += 1
        except Exception as e:
            print(f"Erro ao enviar card ao Anki: {e}")
        finally:
            cleanup_audio([audio_path])

    if sent_cards != settings.card_count:
        print(f"Aviso: {sent_cards}/{settings.card_count} cards criados para '{word}'.")
        if sent_cards:
            print("Confira os cards no Anki antes de tentar novamente; uma nova tentativa pode criar cards adicionais.")
        print("A palavra não foi marcada como concluída.\n")
        return "error"

    try:
        add_word(word)
    except Exception as e:
        print(f"Cards criados, mas erro ao registrar a palavra: {e}\n")
        return "error"
    print(f"\nFinalizado para '{word}'\n")
    return "ok"


def process_words_batch(words, settings: Settings):
    total = len(words)
    results = {"ok": 0, "duplicate": 0, "error": 0, "invalid": 0}

    for index, word in enumerate(words, start=1):
        print(f"\n[{index}/{total}] Palavra: {word}")
        try:
            status = process_word(word, settings)
        except Exception as e:
            print(f"Erro inesperado ao processar '{word}': {e}")
            status = "error"
        results[status] = results.get(status, 0) + 1

    print("\n=== Resumo do processamento ===")
    print(f"Total: {total}")
    print(f"Processadas: {results['ok']}")
    print(f"Duplicadas: {results['duplicate']}")
    print(f"Invalidas: {results['invalid']}")
    print(f"Com erro: {results['error']}\n")


def configure_cards(settings: Settings) -> Settings:
    while True:
        print(f"\nConfiguração atual: dificuldade {settings.difficulty}; {settings.card_count} card(s) por palavra.")
        print("1) Dificuldade")
        print("2) Quantidade de cards")
        print("3) Voltar")
        option = input("Escolha uma opção: ").strip()

        if option in ("3", ""):
            return settings
        if option == "1":
            print("1) Facil (A2/B1)  2) Equilibrado (B1/B2)  3) Avancado (B2/C1)")
            choice = input("Dificuldade (Enter para cancelar): ").strip()
            selected = {"1": "facil", "2": "equilibrado", "3": "avancado"}.get(choice)
            name = "CARD_DIFFICULTY"
        elif option == "2":
            choice = input("Quantidade de cards: 1, 2 ou 3 (Enter para cancelar): ").strip()
            selected = choice if choice in ("1", "2", "3") else None
            name = "CARD_COUNT"
        else:
            print("Opção inválida.")
            continue

        if not choice:
            continue
        if selected is None:
            print("Valor inválido. Nenhuma alteração foi feita.")
            continue

        try:
            save_preset(name, selected)
        except (OSError, ValueError) as e:
            print(f"Não foi possível alterar a configuração: {e}")
            continue

        if name == "CARD_DIFFICULTY":
            settings = replace(settings, difficulty=selected)
        else:
            settings = replace(settings, card_count=int(selected))
        print(f"Configuração salva: {name}={selected}. Já vale para a próxima palavra.")


def main():
    try:
        settings = load_settings()
    except ValueError as e:
        print(f"Configuração inválida: {e}")
        return

    print("=== Kindle to Anki Automation ===")
    print(f"Configuração: {settings.card_count} card(s) por palavra; dificuldade {settings.difficulty}.")
    print("Digite uma palavra (ou 'sair' para encerrar)")
    print("Comandos extras:")
    print("- 'kindle': importar de um banco SQLite")
    print("- 'lote' ou 'batch': inserir varias palavras de uma vez")
    print("- 'config': alterar dificuldade e quantidade de cards\n")

    while True:
        word = input("Palavra: ").strip()

        if word.lower() in ["sair", "exit", "quit"]:
            print("Encerrando...")
            break

        if word.lower() == "config":
            settings = configure_cards(settings)
            continue

        if word.lower() == "kindle":
            db_path = input("Caminho do arquivo .db do Kindle (Enter para o padrão): ").strip().strip('"')
            db_path = db_path or settings.kindle_db_path

            if not db_path:
                print("Caminho invalido\n")
                continue

            limit_text = input("Limite de palavras (Enter para todas): ").strip()
            limit = None
            if limit_text:
                if not limit_text.isdigit() or int(limit_text) <= 0:
                    print("Limite invalido\n")
                    continue
                limit = int(limit_text)

            try:
                kindle_words = extract_words_from_kindle_db(db_path, limit=limit)
            except Exception as e:
                print("Erro ao ler banco do Kindle:", e)
                continue

            if not kindle_words:
                print("Nenhuma palavra encontrada no banco informado\n")
                continue

            print(f"\nEncontradas {len(kindle_words)} palavras no Kindle.")
            process_words_batch(kindle_words, settings)
            continue

        if word.lower() in ["lote", "batch"]:
            raw_words = input(
                "Digite as palavras em uma linha, separadas por espaço, vírgula, ';' ou '|': "
            ).strip()
            parsed_words, invalid_formats = split_words_input(raw_words)

            if invalid_formats:
                print(
                    "Formato invalido detectado (use sem espaco antes de parenteses, ex: match(fosforo)):"
                )
                for invalid in invalid_formats:
                    print(f"- {invalid}")
                print()

            if not parsed_words:
                print("Nenhuma palavra valida foi informada\n")
                continue

            print(f"\nRecebidas {len(parsed_words)} palavras para processar.")
            process_words_batch(parsed_words, settings)
            continue

        if not word:
            print("Digite uma palavra valida\n")
            continue

        process_word(word, settings)


if __name__ == "__main__":
    main()
